"""The discrete memetic GA engine (the two-charge search).

run_ga(fitness_callable, space, params, seed) -> GaRunResult

THE STOP RULE (design decision, 2026-10-13): the engine runs EXACTLY G
generations -- G is an explicit argument of every call, never a
default. There is NO evaluation-budget stop and NO batch truncation
anywhere: every generation completes. The evaluation counts are
recorded CONSEQUENCES, consumed later by the post-hoc GA-vs-brute-
force comparison -- a negative comparison there is a finding, never a
reason to have stopped short.

THE ENGINE IS A PURE BLACK-BOX SEARCH: it calls ONLY the injected
fitness callable (the contract's eval_batch signature
`fitness(idx_i, idx_j, sign_i, sign_j, candidates) -> float64 array`);
it never reads a landscape file, never calls eval_batch_full, never
touches provider internals, and never imports exhaustive_search. The
coordinates come from the injected immutable ga.space.Space. Provider
modules bind the callable: ga.oracle_provider in oracle mode,
fitness.stub in verification, fitness.xtb in live mode. A FRESH
provider instance per run is the RUNNER's duty (a provider's n_evals
ledger is per-run state).

Individuals are canonical row codes (ga.space's row code: the
individual's identity and the landscape's row identity in one integer).
One numpy.random.Generator(PCG64(seed)) per run; every stochastic
choice draws from it in the fixed documented order at each call site.

THE GENERATION CYCLE (the frozen operator set; numeric rates =
ga.params; every generation executes -- no early stop of any kind):

  i.   ELITES: the top n_elite by (f, row code) of the current
       population -- deterministic; their SLOTS are immune to
       displacement this generation.
  ii.  OFFSPRING: ceil((pop_size - n_elite)/2) parent pairs (tournament
       of size tournament_k each), two CHILDREN per pair, generated by
       a PAIR-LEVEL rejection loop: any invalid child re-draws the
       WHOLE attempt with fresh draws, capped at fence_rejection_cap
       attempts -> RuntimeError. Per attempt, ONE crossover event:
       with prob pc the pair exchanges ONE charge's (site, sign) --
       slot c uniform in {1, 2}, shared by both children (child-0 =
       P1 with P2's charge-c; child-1 = P2 with P1's); else both
       children are copies of the parents. Then per child per charge
       slot (slot order 1 then 2), mutation with prob pm, equal
       thirds: site re-sample (uniform over all sites), NN jitter
       (uniform over the VALID subset of the site's nn_k nearest
       sites; empty -> the child is invalid -> pair re-attempt), or
       sign flip. All children pass the space's validity gate.
  iii. EVALUATION: ALL children in ONE batch (batch invariance is a
       contract guarantee).
  iv.  CROWDING PLACEMENT, child by child in order: the child
       replaces, among its two parents AS CAPTURED at pair-generation
       time (fixed geometry), the MORE SIMILAR parent -- the SMALLER
       D = |pos diff| of charge-1 sites + |pos diff| of charge-2
       sites (Euclidean; geometry only, signs excluded; ties prefer
       the pair's first parent) -- unless that parent's slot is
       elite-immune or already taken this generation, then the OTHER
       parent's slot; if neither: the child is DISCARDED. Replacement
       is unconditional (no fitness comparison). Duplicates resolve
       naturally.
  v.   MEMETIC DESCENT on ALL n_elite, in (f, row) order as of the
       generation start, each TO ITS LOCAL OPTIMUM, REMEMBERED
       (decided 2026-10-13): a config in the run's `converged` set is
       skipped at ZERO queries (the budget-protecting rule; a move
       onto a converged config likewise ends that descent). Descent
       step: the neighbourhood = for each charge: (site in {i_c} u
       NN[i_c]) x (sign in {+1, -1}) except the standing one -- at
       most 2 x (9 x 2 - 1) = 34 neighbours; validity-filtered
       (pair-admissible + not fenced; invalid neighbours are
       FILTERED, never re-sampled); deduped; ONE batch per step (all
       COUNTED; the memo serves repeats); the step = the FIRST
       improvement f < f_cur - acceptance_margin (a STRICT
       improvement; margin 0.0 = strictly better; the margin only
       widens) scanning a FRESH shuffle (one permutation draw per
       step). A full pass with no improvement marks the config
       converged for the run. The improved config carries forward in
       the elite slot.
  vi.  LEDGER: (generation, cumulative evaluations, best_f) per
       generation. The best-so-far trajectory is pinned at the in-code
       checkpoints [100, 300, 1000, 3000, 10000, then every 10000] as
       (evaluations, best_f) pairs (evaluations = cumulative queries;
       one entry per consumed checkpoint, at the first batch reaching
       it).

ACCOUNTING (the frozen 02 section-6 semantics, unaltered):
  queries    every fitness-callable row the engine demanded,
             DUPLICATES AND MEMO HITS INCLUDED -- the currency the
             GA-vs-bf comparison is made in ("caching reduces wall
             time, never the count");
  submitted  rows actually placed in successful calls (== the
             provider's n_evals at stop -- the per-run invariant,
             asserted whenever the callable is a bound provider
             method);
  memo_hits  queries - submitted (the GA-layer config-keyed memo
             serves hits, never re-submits them);
  unique     distinct canonical row codes queried (== len(memo)).

With G as the stop rule there is no budget trimming: the counts are
exactly what the run spent, recorded as such. Wording discipline: the
GA spends FITNESS QUERIES.

DETERMINISM -- the fixed draw order at each call site:
  * INIT       per accepted individual: one pair-rank draw, one sign
               draw (a fenced row re-draws BOTH; the rejection cap is
               fence_rejection_cap per individual);
  * OFFSPRING  per pair attempt, in order: P1's tournament (k draws),
               P2's tournament (k draws), one pc uniform, (on cross:
               one crossover-slot draw), then per child per slot in
               the order child0-slot1, child0-slot2, child1-slot1,
               child1-slot2: one pm uniform, (on mutate: one kind
               draw, then the mutation's own draws -- site re-sample:
               one site draw; NN jitter: one index draw into the valid
               subset). The four pm decisions always draw, in order;
               a child already invalidated by an earlier step stays
               invalid (the pair re-attempts).
  * DESCENT    the neighbourhood is deterministic; ONE permutation
               draw per step.

Test seams (default OFF; they draw nothing and advance no state):
  memo=True/False flips the GA-layer memo -- the item-6 ablation
  switch the transfer demonstration needs (memo off: every demanded
  row goes to the callable, submitted == queries, identical values on
  any deterministic provider);
  on_event receives non-advancing diagnostics: ("descent_skip", ...),
  ("descent_end", ...) -- the descent bookkeeping tests ride it.

GaRunResult carries the schema "ga_run_v2" engine fields; run_ga.py
composes + writes the record (atomic write + sha256 sidecar). A
fitness-callable failure is terminal: ProviderFailure (naming the
batch context; a provider error carrying `.config` propagates it) --
no re-execution, no fallback, no penalty values.
"""

import math
import time
from dataclasses import dataclass, field

import numpy as np

__all__ = ["run_ga", "GaRunResult", "ProviderFailure", "CHECKPOINT_BASE",
           "CHECKPOINT_STRIDE"]

# The in-code best-so-far trajectory checkpoints (spec 7): the base
# schedule, then every CHECKPOINT_STRIDE beyond.
CHECKPOINT_BASE = (100, 300, 1000, 3000, 10000)
CHECKPOINT_STRIDE = 10000

SCHEMA = "ga_run_v2"


class ProviderFailure(RuntimeError):
    """A fitness-callable failure during a run: terminal, fail-hard,
    no re-execution (the pre-registered domain rule: e.g. an SCC
    non-convergence exclusion is recorded + the run stops; it is never
    re-run and never penalised).

    Carries the provider's own error (`.provider_error`; a
    SccDomainExclusion-like error exposing `.config` propagates the
    failing config's identity), plus the batch context (`.batch_rows`,
    `.batch_labels`) and, once assembled, the partial run state
    (`.partial`) for the status:failed record.
    """

    def __init__(self, message, provider_error=None, batch_rows=None,
                 batch_labels=None):
        super().__init__(message)
        self.provider_error = provider_error
        self.batch_rows = list(batch_rows or [])
        self.batch_labels = list(batch_labels or [])
        self.partial = None


@dataclass
class GaRunResult:
    """The engine-side result of one GA run (the "ga_run_v2" record's
    engine fields; run_ga.py composes + writes the file)."""

    schema: str = SCHEMA
    params: dict = field(default_factory=dict)
    seed: int = 0
    generations: int = 0                 # G (planned; the stop rule)
    generations_executed: int = 0
    queries: int = 0
    submitted: int = 0
    memo_hits: int = 0
    unique: int = 0
    n_evals_provider: object = None      # the bound provider's counter
    ledger: list = field(default_factory=list)     # [gen, queries, best_f]
    trajectory: list = field(default_factory=list)  # [evaluations, best_f]
    best_row: int = -1
    best_i: int = -1
    best_j: int = -1
    best_s1: int = 0
    best_s2: int = 0
    best_f: float = 0.0
    wall_seconds: float = 0.0
    n_converged: int = 0

    def as_dict(self):
        return {
            "schema": self.schema,
            "params": dict(self.params),
            "seed": self.seed,
            "generations": self.generations,
            "generations_executed": self.generations_executed,
            "counts": {
                "queries": self.queries,
                "submitted": self.submitted,
                "memo_hits": self.memo_hits,
                "unique": self.unique,
                "n_evals_provider": self.n_evals_provider,
            },
            "ledger": [list(e) for e in self.ledger],
            "trajectory": [list(e) for e in self.trajectory],
            "best": {
                "row": self.best_row,
                "config": [self.best_i, self.best_j,
                           self.best_s1, self.best_s2],
                "f": self.best_f,
            },
            "wall_seconds": self.wall_seconds,
            "n_converged": self.n_converged,
        }


def _checkpoint_consumer():
    """The in-code checkpoint schedule: [100, 300, 1000, 3000, 10000]
    then every 10000. Returns consume(count) -> the checkpoints <=
    count not yet consumed (extending lazily)."""
    state = {"pending": list(CHECKPOINT_BASE), "next_mult": 2}

    def consume(count):
        due = []
        while True:
            if not state["pending"]:
                state["pending"].append(state["next_mult"] * CHECKPOINT_STRIDE)
                state["next_mult"] += 1
            c = state["pending"][0]
            if c <= count:
                due.append(c)
                state["pending"].pop(0)
            else:
                return due

    return consume


class _Run:
    """One run's mutable search state (scoped; run_ga delegates here)."""

    def __init__(self, fitness_callable, space, params, seed):
        if params.nn_k != space.nn_k:
            raise ValueError(
                f"incoherent call: params.nn_k = {params.nn_k} != "
                f"space.nn_k = {space.nn_k} (build the Space with the "
                "params' nn_k)")
        if space.n_pairs < 1:
            raise RuntimeError(
                "the space keeps no admissible pair: no configuration "
                "is searchable")
        self.fitness = fitness_callable
        self.space = space
        self.params = params
        self.rng = np.random.Generator(np.random.PCG64(seed))
        self.seed = int(seed)
        self.memo = {}                        # canonical row -> f
        self.use_memo = True
        self.converged = set()                # configs at their local optimum
        self.queries = 0
        self.submitted = 0
        self.unique_set = set()
        self.best_row = -1
        self.best_f = float("inf")
        self.ledger = []
        self.trajectory = []
        self._consume = _checkpoint_consumer()
        self._cand = space.candidates
        # the bound provider behind the callable, when there is one
        # (the per-run invariant check runs against its n_evals)
        self._provider = getattr(fitness_callable, "__self__", None)

    # -- accounting + evaluation -----------------------------------------

    def _demand(self, rows):
        """Serve a batch of canonical row codes (duplicates allowed).

        Counting: every demanded row is a QUERY (duplicates + memo
        hits included); only the rows that actually go to the callable
        are SUBMITTED. Returns {row: f} for the demand."""
        rows = [int(r) for r in rows]
        if not rows:
            return {}
        self.queries += len(rows)
        self.unique_set.update(rows)
        if self.use_memo:
            send = [r for r in dict.fromkeys(rows) if r not in self.memo]
        else:
            send = rows
        served = {}
        if send:
            idx_i, idx_j, sign_i, sign_j = self.space.decode_rows(send)
            try:
                fvals = self.fitness(idx_i, idx_j, sign_i, sign_j,
                                     self._cand)
            except Exception as exc:
                labels = [
                    f"(idx_i={int(a)}, idx_j={int(b)}, "
                    f"sign_i={int(x):+d}, sign_j={int(y):+d})"
                    for a, b, x, y in zip(idx_i, idx_j, sign_i, sign_j)]
                raise ProviderFailure(
                    f"the fitness callable failed at a batch of "
                    f"{len(send)} configuration(s) "
                    f"(first: {labels[0] if labels else '-'}) "
                    f"[cumulative queries so far: {self.queries}] "
                    f"-- {type(exc).__name__}: {exc}",
                    provider_error=exc, batch_rows=send,
                    batch_labels=labels) from exc
            fvals = np.asarray(fvals, dtype=np.float64)
            if fvals.shape != (len(send),):
                raise ProviderFailure(
                    f"the fitness callable returned shape {fvals.shape} "
                    f"for a batch of {len(send)} rows")
            self.submitted += len(send)
            pairs = list(zip(send, (float(v) for v in fvals)))
        else:
            pairs = []
        if self.use_memo:
            for r, v in pairs:
                self.memo[r] = v
            served = {r: self.memo[r] for r in rows}
        else:
            served = dict(pairs)
        for r in rows:
            v = served[r]
            if v < self.best_f or (v == self.best_f
                                   and int(r) < self.best_row):
                self.best_f = v
                self.best_row = int(r)
        # the trajectory pins at the in-code checkpoints, at batch
        # resolution (one entry per consumed checkpoint)
        for _c in self._consume(self.queries):
            self.trajectory.append([self.queries, self.best_f])
        return served

    def _check_provider_invariant(self):
        if self._provider is not None and hasattr(self._provider, "n_evals"):
            n = int(self._provider.n_evals)
            if n != self.submitted:
                raise RuntimeError(
                    f"accounting invariant broken: provider.n_evals "
                    f"({n}) != submitted ({self.submitted}) -- a shared "
                    "provider instance or an unaccounted call")
        return self._provider

    # -- operators ---------------------------------------------------------

    def _tournament(self, k):
        """One tournament: k iid slot draws; winner = min (f, row)."""
        best_slot = None
        best_key = None
        for _ in range(k):
            s = int(self.rng.integers(0, self.params.pop_size))
            key = (self.pop_f[s], int(self.pop_rows[s]))
            if best_key is None or key < best_key:
                best_key = key
                best_slot = s
        return best_slot

    def _jitter_valid_subset(self, raw, slot):
        """The valid site subset of the slot's standing site's NN row
        (against the CURRENT raw config). Empty -> None (the child is
        invalid -> pair re-attempt)."""
        si = slot - 1
        base = raw[si]
        valid = []
        for nb in self.space.nn[base]:
            trial = list(raw)
            trial[si] = int(nb)
            if self.space.encode(trial[0], trial[1], trial[2], trial[3]) >= 0:
                valid.append(int(nb))
        return valid or None

    def _offspring_pair(self):
        """One parent pair's two children via the pair-level rejection
        loop (fresh draws per attempt). -> ([raw0, raw1], slotA, sitesA,
        slotB, sitesB). Raises RuntimeError on cap exhaustion."""
        cap = self.params.fence_rejection_cap
        pop = self.params.pop_size
        k = self.params.tournament_k
        for _attempt in range(cap):
            slot_a = self._tournament(k)
            slot_b = self._tournament(k)
            p1 = list(self.space.decode(int(self.pop_rows[slot_a])))
            p2 = list(self.space.decode(int(self.pop_rows[slot_b])))
            # ONE crossover event per pair
            if self.rng.random() < self.params.pc:
                c = int(self.rng.integers(0, 2))           # slot in {1, 2}
                si, gi = c - 1, c + 1                       # site / sign idx
                child0 = list(p1)
                child0[si], child0[gi] = p2[si], p2[gi]
                child1 = list(p2)
                child1[si], child1[gi] = p1[si], p1[gi]
            else:
                child0, child1 = list(p1), list(p2)
            # per child per charge slot (order 1 then 2): mutation
            for child in (child0, child1):
                for slot in (1, 2):
                    if self.rng.random() < self.params.pm:
                        kind = int(self.rng.integers(0, 3))
                        si, gi = slot - 1, slot + 1
                        if kind == 0:      # site re-sample (uniform, all sites)
                            child[si] = int(self.rng.integers(0, self.space.n))
                        elif kind == 1:    # NN jitter (uniform, valid subset)
                            valid = self._jitter_valid_subset(child, slot)
                            if valid is None:
                                child[0] = -1   # poison: the child is invalid
                            else:
                                child[si] = valid[int(
                                    self.rng.integers(0, len(valid)))]
                        else:              # sign flip
                            child[gi] = -child[gi]
            r0 = self.space.encode(child0[0], child0[1], child0[2], child0[3])
            r1 = self.space.encode(child1[0], child1[1], child1[2], child1[3])
            if r0 < 0 or r1 < 0:
                continue                   # any invalid child -> the whole
                                           # pair attempt re-drawn, fresh
            return ([r0, r1], slot_a,
                    (int(p1[0]), int(p1[1])),
                    slot_b, (int(p2[0]), int(p2[1])))
        raise RuntimeError(
            f"offspring: the pair-level rejection cap "
            f"({self.params.fence_rejection_cap} attempts) was exhausted "
            "without two valid children -- the space cannot reproduce")

    def _descent_neighbourhood(self, row):
        """The deduped, validity-filtered <= 34-neighbour list of `row`
        (deterministic enumeration order; the standing config is
        never its own neighbour)."""
        i1, i2, s1, s2 = self.space.decode(row)
        raw = [i1, i2, s1, s2]
        out = []
        seen = {int(row)}
        for slot in (1, 2):
            si, gi = slot - 1, slot + 1
            base_site, base_sign = raw[si], raw[gi]
            sites = [base_site] + [int(x) for x in self.space.nn[base_site]]
            for site in sites:
                for sign in (1, -1):
                    if site == base_site and sign == base_sign:
                        continue           # except the standing one
                    trial = list(raw)
                    trial[si], trial[gi] = site, sign
                    r = self.space.encode(trial[0], trial[1],
                                          trial[2], trial[3])
                    if r < 0 or r in seen:
                        continue           # validity-filtered + deduped
                    seen.add(r)
                    out.append(r)
        return out

    def _descent(self, gen, slot, row0, f0):
        """One elite's descent to its local optimum (remembered).
        Returns (end_row, end_f)."""
        if row0 in self.converged:
            if self.on_event:
                self.on_event("descent_skip", {
                    "generation": gen, "slot": slot, "row": int(row0),
                    "f": f0, "queries_before": self.queries,
                    "queries_after": self.queries})
            return row0, f0
        cur_row, cur_f = int(row0), float(f0)
        while True:
            nb = self._descent_neighbourhood(cur_row)
            if not nb:
                self.converged.add(cur_row)
                break
            served = self._demand(nb)      # ONE batch per step, all counted
            order = self.rng.permutation(len(nb))   # FRESH shuffle per step
            move = None
            for k in order:
                r = nb[int(k)]
                if served[r] < cur_f - self.params.acceptance_margin:
                    move = (r, served[r])
                    break
            if move is None:
                self.converged.add(cur_row)   # a full pass found nothing
                break
            cur_row, cur_f = move
            if cur_row in self.converged:
                break      # a known local optimum: done at zero queries
        if self.on_event:
            self.on_event("descent_end", {
                "generation": gen, "slot": slot,
                "start_row": int(row0), "start_f": float(f0),
                "end_row": int(cur_row), "end_f": float(cur_f),
                "converged_to": int(cur_row) in self.converged,
                "queries_before": self.queries,
                "queries_after": self.queries})
        return cur_row, cur_f

    # -- the run --------------------------------------------------------------

    def run(self, G, on_event=None, memo=True):
        self.on_event = on_event
        self.use_memo = bool(memo)
        params = self.params
        space = self.space
        t0 = time.monotonic()
        if not (isinstance(G, int) and not isinstance(G, bool) and G >= 1):
            raise ValueError(f"G must be an int >= 1 (the explicit stop "
                             f"rule's argument), got {G!r}")

        # --- INIT: pop_size uniform admissible configs, one batch -------
        # Draw order: per accepted individual: one pair-rank draw, one
        # sign draw; a fenced row re-draws BOTH. Rejection skips ONLY
        # the fence; duplicates are allowed (rejection never dedups).
        # The rejection cap is fence_rejection_cap per individual.
        pop_rows = []
        for _ in range(params.pop_size):
            for _attempt in range(params.fence_rejection_cap):
                row = 4 * int(self.rng.integers(0, space.n_pairs)) \
                    + int(self.rng.integers(0, 4))
                if space.row_fenced(row):
                    continue
                pop_rows.append(row)
                break
            else:
                raise RuntimeError(
                    "init: the fence rejection cap was exhausted while "
                    "sampling uniform admissible configurations")
        pop_rows = np.asarray(pop_rows, dtype=np.int64)
        served = self._demand(pop_rows)
        pop_f = np.asarray([served[int(r)] for r in pop_rows], dtype=np.float64)
        self.pop_rows, self.pop_f = pop_rows, pop_f

        # --- the G generations (the primary stop rule: exactly G) -------
        elite_slots = ()
        elites = []
        for g in range(1, G + 1):
            # i. ELITES: top n_elite by (f, row code); immune slots
            order = np.lexsort((self.pop_rows, self.pop_f))
            elite_slots = np.sort(order[: params.n_elite])
            elites = [(int(self.pop_f[s]), int(self.pop_rows[s]), int(s))
                      for s in order[: params.n_elite]]

            # ii. OFFSPRING
            children = []          # (row, slotA, sitesA, slotB, sitesB)
            n_pairs_off = math.ceil((params.pop_size - params.n_elite) / 2)
            for _ in range(n_pairs_off):
                rows, slot_a, sites_a, slot_b, sites_b = self._offspring_pair()
                rows_list = [rows[0], rows[1]]   # child0 then child1
                for r in rows_list:
                    children.append((r, slot_a, sites_a, slot_b, sites_b))

            # iii. EVALUATION: ALL children in ONE batch
            if children:
                served = self._demand([c[0] for c in children])

            # iv. CROWDING PLACEMENT, child by child in order
            taken = set()
            immune = {int(s) for s in elite_slots}
            for row, slot_a, (ai, aj), slot_b, (bi, bj) in children:
                f_child = served[row]
                ci1, ci2, _s1, _s2 = space.decode(row)
                # D: geometry only, vs the parents AS CAPTURED
                d_a = float(np.linalg.norm(
                    self._cand[ci1] - self._cand[ai])) \
                    + float(np.linalg.norm(
                        self._cand[ci2] - self._cand[aj]))
                d_b = float(np.linalg.norm(
                    self._cand[ci1] - self._cand[bi])) \
                    + float(np.linalg.norm(
                        self._cand[ci2] - self._cand[bj]))
                pref, other = ((slot_a, slot_b) if d_a <= d_b
                               else (slot_b, slot_a))
                target = None
                for cand_slot in (pref, other):
                    if cand_slot in immune or cand_slot in taken:
                        continue
                    target = cand_slot
                    break
                if target is None:
                    continue          # the child is DISCARDED
                self.pop_rows[target] = row
                self.pop_f[target] = f_child
                taken.add(target)

            # v. MEMETIC DESCENT on ALL n_elite, in (f, row) order
            if params.use_descent:
                for f_e, row_e, slot_e in elites:
                    new_row, new_f = self._descent(g, slot_e, row_e, f_e)
                    self.pop_rows[slot_e] = new_row
                    self.pop_f[slot_e] = new_f

            # vi. LEDGER
            self.ledger.append([g, self.queries, self.best_f])

        self._check_provider_invariant()
        i, j, s1, s2 = space.decode(self.best_row)
        return GaRunResult(
            params=params.as_dict(), seed=self.seed, generations=G,
            generations_executed=G, queries=self.queries,
            submitted=self.submitted,
            memo_hits=self.queries - self.submitted,
            unique=len(self.unique_set),
            n_evals_provider=(int(self._provider.n_evals)
                              if (self._provider is not None
                                  and hasattr(self._provider, "n_evals"))
                              else None),
            ledger=self.ledger, trajectory=self.trajectory,
            best_row=int(self.best_row), best_i=i, best_j=j,
            best_s1=s1, best_s2=s2, best_f=self.best_f,
            wall_seconds=round(time.monotonic() - t0, 6),
            n_converged=len(self.converged))

    def partial_state(self, G):
        """The run state at a terminal failure (for the status:failed
        record): everything recorded so far."""
        i, j, s1, s2 = (self.space.decode(self.best_row)
                        if self.best_row >= 0 else (-1, -1, 0, 0))
        return GaRunResult(
            params=self.params.as_dict(), seed=self.seed, generations=G,
            generations_executed=len(self.ledger), queries=self.queries,
            submitted=self.submitted,
            memo_hits=self.queries - self.submitted,
            unique=len(self.unique_set),
            n_evals_provider=(int(self._provider.n_evals)
                              if (self._provider is not None
                                  and hasattr(self._provider, "n_evals"))
                              else None),
            ledger=self.ledger, trajectory=self.trajectory,
            best_row=int(self.best_row), best_i=i, best_j=j,
            best_s1=s1, best_s2=s2,
            best_f=(self.best_f if self.best_row >= 0 else float("nan")),
            wall_seconds=round(time.monotonic() - self._t0, 6),
            n_converged=len(self.converged))


def run_ga(fitness_callable, space, params, seed, *, G, memo=True,
           on_event=None):
    """One GA run: exactly G generations (the explicit stop rule).

    fitness_callable  the contract's eval_batch signature
                      (idx_i, idx_j, sign_i, sign_j, candidates) ->
                      float64 array; a black-box view only
    space             an immutable ga.space.Space (d_min + row code +
                      NN table + fence)
    params            a frozen ga.params.GAParams
    seed              the run's PCG64 seed
    G                 the generation count -- an explicit argument of
                      every run, never a default (the stop rule,
                      2026-10-13)
    memo              the GA-layer config-keyed memo (ablation switch;
                      off => every demanded row goes to the callable)
    on_event          diagnostic hook (draws nothing; test seam)

    Returns GaRunResult. A fitness-callable failure raises
    ProviderFailure (terminal; the partial state rides .partial)."""
    run = _Run(fitness_callable, space, params, seed)
    run._t0 = time.monotonic()
    try:
        return run.run(G, on_event=on_event, memo=memo)
    except ProviderFailure as exc:
        exc.partial = run.partial_state(G)
        raise